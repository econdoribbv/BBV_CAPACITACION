'use strict';
const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { startServer, tempDirectory, unzip } = require('./helpers.cjs');

(async () => {
  const directory = tempDirectory('ui-');
  const artifacts = path.resolve(__dirname, '../test-results');
  fs.mkdirSync(artifacts, { recursive: true });
  const server = await startServer(directory);
  let browser;
  try {
    browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE_PATH || undefined });
    const context = await browser.newContext({ viewport: { width: 1440, height: 960 }, acceptDownloads: true });
    const errors = [];
    context.on('page', (page) => page.on('pageerror', (error) => errors.push(error.message)));
    const participant = await context.newPage();
    await participant.goto(server.url);
    await participant.locator('.max-image').waitFor();
    await participant.waitForFunction(() => document.querySelector('.max-image').naturalWidth === 500);
    await participant.screenshot({ path: path.join(artifacts, 'landing-desktop.png'), fullPage: true });
    await participant.setViewportSize({ width: 390, height: 844 });
    assert.ok(await participant.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile landing overflow');
    await participant.screenshot({ path: path.join(artifacts, 'landing-mobile.png'), fullPage: true });
    await participant.getByLabel('Nombre completo').fill('Ana García');
    await participant.getByLabel('Correo electrónico').fill('ana@example.test');
    await participant.getByLabel('Género', { exact: true }).selectOption('Femenino');
    await participant.getByLabel('Rango de edad').selectOption('26-36');
    await participant.getByRole('button', { name: 'Registrarme y entrar' }).click();
    await participant.waitForURL('**/participant.html');
    await participant.locator('#greeting').filter({ hasText: 'Ana' }).waitFor();
    assert.equal(await participant.locator('#rank').count(), 0, 'the player view never shows a position');
    for (const [name, email] of [['Bruno Díaz', 'bruno@example.test'], ['Carla Rojas', 'carla@example.test']]) {
      const res = await fetch(server.url + '/api/register', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ name, email, gender: 'Otro', ageRange: '18-25' }) });
      assert.equal(res.status, 201);
    }

    const staff = await context.newPage();
    await staff.goto(server.url + '/admin.html');
    await staff.locator('#username').fill('admin');
    await staff.locator('#password').fill('integration-only');
    await staff.locator('#loginForm button').click();
    await staff.waitForURL('**/admin.html');
    await staff.locator('#statAttendees').filter({ hasText: '3' }).waitFor();
    await staff.locator('.nav [data-section="participantes"]').click();
    await staff.locator('#participantSearch').fill('nadie-coincide');
    const excelPromise = staff.waitForEvent('download');
    await staff.locator('#exportExcel').click();
    const excel = await excelPromise;
    assert.match(excel.suggestedFilename(), /^participantes-bbv-.*\.xlsx$/);
    assert.match(unzip(fs.readFileSync(await excel.path()))['xl/worksheets/sheet1.xml'], /ana@example.test/);
    const backupPromise = staff.waitForEvent('download');
    await staff.locator('#exportBackup').click();
    const backup = await backupPromise;
    assert.equal(JSON.parse(fs.readFileSync(await backup.path(), 'utf8')).attendees.length, 3);
    await staff.locator('#participantSearch').fill('');
    await staff.screenshot({ path: path.join(artifacts, 'admin-desktop.png'), fullPage: true });
    await staff.setViewportSize({ width: 390, height: 844 });
    assert.ok(await staff.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'mobile admin overflow');
    await staff.screenshot({ path: path.join(artifacts, 'admin-mobile.png'), fullPage: true });
    await staff.setViewportSize({ width: 1440, height: 960 });
    assert.equal((await staff.request.post(server.url + '/api/admin/game/start')).status(), 200);
    const projector = await context.newPage();
    await projector.goto(server.url + '/projector.html');
    await participant.locator('[data-answer="1"]').click();
    await participant.locator('.answer-state').filter({ hasText: 'Respuesta enviada' }).waitFor();
    await projector.locator('#projectorTimer').waitFor();
    await projector.screenshot({ path: path.join(artifacts, 'projector-question.png') });
    assert.equal((await staff.request.post(server.url + '/api/admin/game/finish')).status(), 200);
    await projector.locator('.projector-leaders').filter({ hasText: 'Pasan a la ruleta' }).waitFor();
    await projector.locator('.confetti').first().waitFor({ state: 'attached' });
    await projector.waitForTimeout(1500);
    await projector.screenshot({ path: path.join(artifacts, 'projector-finished.png') });
    // The projection opens the wheel by itself after showing the winners.
    await projector.locator('iframe.wheel-overlay').waitFor({ timeout: 12000 });
    await participant.locator('.waiting').filter({ hasText: 'Gracias por participar' }).waitFor();
    assert.equal((await participant.locator('#gameCard').innerText()).includes('posición'), false);
    await participant.screenshot({ path: path.join(artifacts, 'participant-finished.png'), fullPage: true });
    await projector.close();
    await staff.goto(server.url + '/wheel.html');
    await staff.locator('#turnName').filter({ hasText: 'Ana García' }).waitFor();
    assert.equal(await staff.locator('.inventory-count').count(), 0, 'the projected wheel never shows prize counts');
    await staff.screenshot({ path: path.join(artifacts, 'wheel-desktop.png'), fullPage: true });
    const spinResponse = staff.waitForResponse((response) => response.url().endsWith('/api/admin/wheel/spin'));
    assert.equal(await staff.locator('#spinButton').textContent(), 'Girar ruleta');
    assert.equal((await staff.locator('body').innerText()).toLowerCase().includes('torito'), false);
    const spinStarted = Date.now();
    await staff.locator('#bullButton').click();
    const spin = await (await spinResponse).json();
    await staff.locator('.is-gripping').waitFor();
    const gripError = await staff.locator('.max-motion-layer').evaluate((el) => {
      const d = el.dataset;
      return Math.abs(Math.hypot(Number(d.handX)-Number(d.rimX), Number(d.handY)-Number(d.rimY))-Number(d.radius));
    });
    assert.ok(gripError < .1, 'MAX hand must touch the rim while gripping');
    await staff.screenshot({ path: path.join(artifacts, 'wheel-grip.png'), fullPage: true });
    await staff.locator('.is-spinning').waitFor();
    await staff.screenshot({ path: path.join(artifacts, 'wheel-spinning.png'), fullPage: true });
    await staff.locator('#winnerModal.show').waitFor({ timeout: 15000 });
    assert.ok(Date.now()-spinStarted >= 9500, 'The full spin must last longer than the old five-second animation');
    assert.equal(await staff.locator('#winnerPrize').textContent(), spin.prize.name);
    await staff.locator('.winner-stage').evaluate(async (el) => { await Promise.all(el.getAnimations().map((a) => a.finished)); });
    await staff.screenshot({ path: path.join(artifacts, 'winner-max.png'), fullPage: true });
    await staff.locator('#closeWinner').click();
    await staff.waitForFunction(() => getComputedStyle(document.querySelector('#winnerModal')).opacity === '0');
    await staff.locator('.confetti').first().waitFor({ state: 'detached' });
    await staff.setViewportSize({ width: 390, height: 844 });
    await staff.screenshot({ path: path.join(artifacts, 'wheel-mobile.png'), fullPage: true });
    const overflow = await staff.evaluate(() => [...document.querySelectorAll('body *')].filter((node) => {
      const r = node.getBoundingClientRect(); return r.right > innerWidth + 1 && getComputedStyle(node).position !== 'fixed' && !node.closest('.depth-scene');
    }).map((node) => ({ tag: node.tagName, class: node.getAttribute('class'), right: node.getBoundingClientRect().right })));
    assert.ok(await staff.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `mobile wheel overflow: ${JSON.stringify(overflow)}`);
    staff.once('dialog', (dialog) => dialog.accept());
    await staff.locator('.undo-spin').click();
    await staff.locator('#turnName').filter({ hasText: 'Ana García' }).waitFor();
    await staff.locator('#centerSpin').click();
    await staff.locator('.is-gripping').waitFor();
    const mobileContactError = await staff.evaluate(() => {
      const a = document.querySelector('.wheel-area').getBoundingClientRect();
      const w = document.querySelector('.wheel-wrap').getBoundingClientRect();
      const d = document.querySelector('.max-motion-layer').dataset;
      return Math.abs(Math.hypot(Number(d.handX)-(w.left-a.left+w.width/2), Number(d.handY)-(w.top-a.top+w.height/2))-(w.width/2+9));
    });
    assert.ok(mobileContactError < .1, 'MAX must grip the actual rim on a second spin at mobile size');
    await staff.screenshot({ path: path.join(artifacts, 'wheel-grip-mobile.png'), fullPage: true });
    await staff.locator('#winnerModal.show').waitFor({ timeout: 15000 });
    await staff.locator('#closeWinner').click();
    await staff.emulateMedia({ reducedMotion: 'reduce' });
    assert.equal(await staff.locator('.bull-body').evaluate((node) => getComputedStyle(node).animationName), 'none');
    await staff.locator('.max-still').waitFor({ state: 'visible' });
    assert.equal(await staff.locator('.max-image').isVisible(), false);
    await staff.goto(server.url + '/admin.html#participantes');
    await staff.locator('#exportExcel').waitFor();
    await context.clearCookies();
    await staff.locator('#exportExcel').click();
    await staff.waitForURL('**/login.html?next=*');
    assert.equal(new URL(staff.url()).searchParams.get('next'), '/admin.html#participantes');
    assert.deepEqual(errors, []);
    console.log('UI OK: mobile + desktop, registration, automatic game end with confetti, wheel overlay, center spin, Excel/JSON downloads, reduced motion and expired-session redirect.');
  } finally {
    await browser?.close(); await server.stop();
    fs.rmSync(directory, { recursive: true, force: true });
  }
})().catch((error) => { console.error(error); process.exitCode = 1; });
